package ru.get.tms.domain.task;

/**
 * Приоритеты задачи.
 *
 * <p>Енум определяет уровни важности задач:
 *
 * <ul>
 *   <li>URGENT - срочно (красный)
 *   <li>HIGH - высокий (оранжевый)
 *   <li>MEDIUM - средний (желтый)
 *   <li>LOW - низкий (зеленый)
 * </ul>
 */
public enum TaskPriority {
  /** Срочная задача, требует немедленного внимания. */
  URGENT,

  /** Задача с высоким приоритетом. */
  HIGH,

  /** Задача со средним приоритетом (по умолчанию). */
  MEDIUM,

  /** Задача с низким приоритетом. */
  LOW
}
