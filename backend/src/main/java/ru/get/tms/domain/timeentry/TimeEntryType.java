package ru.get.tms.domain.timeentry;

/**
 * Типы записей времени.
 *
 * <p>Енум определяет способ создания записи времени:
 *
 * <ul>
 *   <li>TIMER - запись создана через таймер (автоматическое время начала/окончания)
 *   <li>MANUAL - запись создана вручную пользователем
 * </ul>
 */
public enum TimeEntryType {
  /** Запись создана через автоматический таймер. */
  TIMER,

  /** Запись создана вручную пользователем. */
  MANUAL
}
